    .equ SDREADYX, 0x9B0A
    .equ SDWAITX, 0x9B0C
    .equ SDVALUE, 0x9B0E
    .equ SDWAITMASK, 0x9B0F
    .equ SDWAITVALUE, 0x9B10
    .equ SDPREVSEQ, 0x9B11
