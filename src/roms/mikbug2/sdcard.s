SDCHECKFAIL: LDAB #0x08
 SEC
 RTS
SDFAIL: LDAB #0x10
 SEC
SDRETURN: RTS
; Preserve payload A while accumulating unsigned bytes into a 16-bit sum.
SDADD: PSHA
 ADDA SDSUM+1
 STAA SDSUM+1
 BCC SDADDDONE
 INC SDSUM
SDADDDONE: PULA
 RTS
; READY checks INFO version/geometry and mounted-media status.
SDREADY: STX SDREADYX
 JSR SDCHECK
 LDX SDREADYX
 TSTB
 BEQ SDREADYOK
 SEC
 RTS
SDREADYOK: CLC
 RTS
SDCHECK: LDAA #0
 JSR SDCOMMAND
 BCS SDCHECKRETURN
 CLR SDINDEX
SDINFOLOOP: JSR SDGET
 BCS SDCHECKRETURN
 LDX #SDINFO
 LDAB SDINDEX
SDINFOINDEX: TSTB
 BEQ SDINFOCOMPARE
 INX
 DECB
 BRA SDINFOINDEX
SDINFOCOMPARE: CMPA 0,X
 BNE SDINFOMISMATCH
 INC SDINDEX
 LDAB SDINDEX
 CMPB #6
 BNE SDINFOLOOP
 LDAA #1
 JSR SDCOMMAND
 BCS SDCHECKRETURN
 JSR SDGET
 BCS SDCHECKRETURN
 TSTA
 BNE SDFAIL
 JMP SDOK
; Consume the remaining INFO bytes even when the geometry is wrong.
SDINFOMISMATCH: INC SDINDEX
SDINFODRAIN: LDAB SDINDEX
 CMPB #6
 BEQ SDFAIL
 JSR SDGET
 BCS SDCHECKRETURN
 INC SDINDEX
 BRA SDINFODRAIN
SDCHECKRETURN: RTS
; A command is written to $E080; parameters/payload go to $E081.
SDCOMMAND: STAA SDVALUE
 JSR SDWAITRX
 BCS SDPACKETRETURN
 LDAA SDVALUE
 STAA SDPORT_COMMAND
 JSR SDWAITRXACK
 BCS SDPACKETRETURN
 LDAA SDVALUE
 CLC
SDPACKETRETURN: RTS
SDPUT: STAA SDVALUE
 JSR SDWAITRX
 BCS SDPUTRETURN
 LDAA SDVALUE
 STAA SDPORT_DATA
 JSR SDWAITRXACK
 BCS SDPUTRETURN
 LDAA SDVALUE
 CLC
SDPUTRETURN: RTS
; Read one response byte, then wait until the AVR acknowledges consumption.
SDGET: JSR SDWAITTX
 BCS SDGETRETURN
 LDAA SDPORT_DATA
 STAA SDVALUE
 JSR SDWAITTXACK
 BCS SDGETRETURN
 LDAA SDVALUE
 CLC
SDGETRETURN: RTS
; Wait for a write slot and remember its current RX_SEQUENCE value.
SDWAITRX: LDAA #SD_RX_SPACE
 STAA SDWAITMASK
 STAA SDWAITVALUE
 JSR SDWAIT
 BCS SDWAITRETURN
 LDAA SDPORT_STATUS
 ANDA #SD_RX_SEQUENCE
 STAA SDPREVSEQ
 CLC
SDWAITRETURN: RTS
SDWAITRXACK: LDAA #SD_RX_SEQUENCE
 STAA SDWAITMASK
 LDAA SDPREVSEQ
 EORA #SD_RX_SEQUENCE
 STAA SDWAITVALUE
 JMP SDWAIT
; Wait for a response byte and remember its current TX_SEQUENCE value.
SDWAITTX: LDAA #SD_TX_VALID
 STAA SDWAITMASK
 STAA SDWAITVALUE
 JSR SDWAIT
 BCS SDWAITRETURN
 LDAA SDPORT_STATUS
 ANDA #SD_TX_SEQUENCE
 STAA SDPREVSEQ
 CLC
 RTS
SDWAITTXACK: LDAA #SD_TX_SEQUENCE
 STAA SDWAITMASK
 LDAA SDPREVSEQ
 EORA #SD_TX_SEQUENCE
 STAA SDWAITVALUE
 JMP SDWAIT
; Bounded status poll. Preserve caller X and B on success.
SDWAIT: STX SDWAITX
 PSHB
 LDAB #4*SD_CPU_MHZ
SDWAITOUTER: LDX #0
SDWAITLOOP: LDAA SDPORT_STATUS
 ANDA SDWAITMASK
 CMPA SDWAITVALUE
 BEQ SDWAITOK
 DEX
 BNE SDWAITLOOP
 DECB
 BNE SDWAITOUTER
 PULB
 LDX SDWAITX
 JMP SDERROR
SDWAITOK: PULB
 LDX SDWAITX
 CLC
 RTS
