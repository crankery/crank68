#!/usr/bin/env python3
"""Generate the V1-3 opcode metadata; handler bodies live in z/handlers.s. No opcode semantics are implemented here.
Source: https://inform-fiction.org/zmachine/standards/z1point1/sect14.html
Run from any directory. --check verifies that checked-in output is current.
"""
from pathlib import Path
import sys

# number:name:flags:minimum-version. S=store, B=branch, T=inline text,
# I=indirect variable reference (not ordinary variable-value resolution).
GROUPS = {
    '0op': '''0:rtrue:-:1 1:rfalse:-:1 2:print:T:1 3:print_ret:T:1
4:nop:-:1 5:save:B:1 6:restore:B:1 7:restart:-:1 8:ret_popped:-:1
9:pop:-:1 A:quit:-:1 B:new_line:-:1 C:show_status:-:3 D:verify:B:3''',
    '1op': '''0:jz:B:1 1:get_sibling:SB:1 2:get_child:SB:1 3:get_parent:S:1
4:get_prop_len:S:1 5:inc:I:1 6:dec:I:1 7:print_addr:-:1
9:remove_obj:-:1 A:print_obj:-:1 B:ret:-:1 C:jump:-:1 D:print_paddr:-:1
E:load:SI:1 F:not:S:1''',
    '2op': '''1:je:B:1 2:jl:B:1 3:jg:B:1 4:dec_chk:BI:1 5:inc_chk:BI:1
6:jin:B:1 7:test:B:1 8:or:S:1 9:and:S:1 A:test_attr:B:1
B:set_attr:-:1 C:clear_attr:-:1 D:store:I:1 E:insert_obj:-:1
F:loadw:S:1 10:loadb:S:1 11:get_prop:S:1 12:get_prop_addr:S:1
13:get_next_prop:S:1 14:add:S:1 15:sub:S:1 16:mul:S:1 17:div:S:1 18:mod:S:1''',
    'var': '''0:call:S:1 1:storew:-:1 2:storeb:-:1 3:put_prop:-:1 4:sread:-:1
5:print_char:-:1 6:print_num:-:1 7:random:S:1 8:push:-:1 9:pull:I:1
A:split_window:-:3 B:set_window:-:3 13:output_stream:-:3
14:input_stream:-:3 15:sound_effect:-:3''',
}
BITS = {'S': 1, 'B': 2, 'T': 4, 'I': 8}


def generate():
    rows = {}
    for group, entries in GROUPS.items():
        rows[group] = {}
        for entry in entries.split():
            number, name, flags, version = entry.split(':')
            rows[group][int(number, 16)] = (name, flags, int(version))
    lines = ['; Generated by tools/make-opcodes.py; edit the manifest there.',
             '; Descriptors: handler word, flags byte, minimum-version byte.',
             '; Four groups of 32 slots; reserved/V4+ slots are invalid.',
             '; sound_effect is included for the V3 Lurking Horror exception.',
             'opcode_tables:']
    for group, entries in rows.items():
        lines.append(f'opcode_{group}:')
        for number in range(32):
            if number in entries:
                name, flags, version = entries[number]
                bits = sum(BITS.get(c, 0) for c in flags)
                lines.extend([f'        .word op_{name}', f'        .byte {bits},{version} ; {group.upper()}:{number:02X} {name}'])
            else:
                lines.extend(['        .word op_invalid', '        .byte 0,0'])
    lines.append('opcode_tables_end:')
    for entries in rows.values():
        for name, _, _ in entries.values():
            lines.extend([f'op_name_{name}:', f'        .ascii "{name}"', '        .byte 0'])
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    target = Path(__file__).resolve().parents[1] / 'z' / 'opcodes.s'
    result = generate()
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != result:
            raise SystemExit('Opcode scaffold is stale: run z68/tools/make-opcodes.py')
    else:
        target.write_text(result)
