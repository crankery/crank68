 BRA DOTR22
DOTR21 LDAA #MAXS1 MAX DOUBLE SIDED
DOTR22 STAA AVLP+10,X
 LDAA #MAXTRK-1
 STAA AVLP+9,X
 LDAA SMONTH
 LDAB SDAYMN
 STAA AVLP+6,X
 STAB AVLP+7,X
 LDAA SYEARN
