* INITIALIZE DIRECTORY

DIRINT LDX #WORK
 TST DBSDF
 BNE DIRIN1 BR IF DOUBLE SIDED
 LDAA #MAXS0 MAX SECTORS
 BRA DIRIN2
DIRIN1 LDAA #MAXS1 MAX SECTORS DOUBLE SIDED
DIRIN2 STAA FCS+1,X
 JSR READSS READ IN SECTOR
 BNE DOTRK4 ERRORS?
 LDX #WORK RESTORE POINTER
 CLR FSB,X CLEAR LINK
 CLR FSB+1,X
 JSR WRITSS WRITE SECTOR BACK
 BNE DOTRK4 ERRORS?

* SAVE BOOT ON TRACK 0 SECTOR 0

DOBOOT LDX #BOOT POINT TO LOADER
 CLRA TRACK #0
 CLRB SECTOR #0
 JSR DWRITE WRITE THE SECTOR
 BNE DOTRK4 ERRORS?

* REPORT TOTAL SECTORS AND EXIT

 LDX #WORK SETUP AN FCB
 LDAA #16 OPEN SIR FUNCTION
 STAA 0,X
 JSR FMSCAL OPEN SIR
 BNE DOTRK4
 LDAA #7 GET INFO RECORD FUNCTION
 STAA 0,X
 JSR FMSCAL GET 1ST INFO RECORD
 BNE DOTRK4
 LDX #CMPLTE FORMATTING COMPLETE
 JSR PSTRNG REPORT IT
 LDX #WORK+21 TOTAL IS IN INFO RECORD
 CLRB
 JSR OUTDEC
 JMP WARMST ALL FINISHED!

