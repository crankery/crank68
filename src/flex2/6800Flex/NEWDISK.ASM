* ACTUAL FORMAT ROUTINE

 LDX #WORK
FORM30 CLR 0,X CLEAR RAM BUFFER
 INX 
 CPX #SWKEND
 BNE FORM30
 NOP 
 SEI 
 CLR TRACK
 CLR SIDE

FORM32 LDX #WORK+2
 TST SIDE
 BNE FORM4
 CLR SECTOR
FORM4 BSR DOSEC PROCESS RAM WITH INFO
 INC SECTOR ADVANCE TO NEXT
 LDAA SECTOR CHECK VALUE
 TST SIDE CHECK SIDE
 BNE FORM45
 CMPA #MAXS0
 BNE FORM4 REPEAT UNTIL LAST SECTOR
 BRA FORM47
FORM45 CMPA #MAXS1
 BNE FORM4 REPEAT UNTIL LAST SECTOR
FORM47 JSR WRTTRK
 TST DBSDF ONE SIDE?
 BEQ FORM6
 TST SIDE
 BNE FORM6
 INC SIDE
 BRA FORM32

FORM6 INC TRACK
 LDAA TRACK
 CMPA #MAXTRK
 BNE FORM7 REPEAT UNTIL LAST TRACK
 JMP SETUP DONE...GO FINISH UP

FORM7 STAA TRACK
 JSR SEEK
 CLR SIDE
 BRA FORM32

* EXIT ROUTINES

EXIT LDX #ABORTS
EXIT2 JSR PSTRNG
 JMP WARMST
EXIT4 LDX #WPST WRITE PROTECTED
 BRA EXIT2

* PROCESS SECTOR IN RAM

DOSEC LDAA #$FE ID ADDRESS MARK
 STAA 6,X
 LDAA #1 SECTOR NUMBER
 STAA 10,X
 LDAA TRACK
 STAA 7,X
 LDAB SECTOR
 STX INDEX1 SAVE INDEX
 LDX #SSMAP5 POINT TO CORRECT MAP
 BSR ADDXB POINT TO SECTOR NUMBER
 LDAB 0,X GET SECTOR NUMBER
 LDX INDEX1 RESTOR INDEX
 TST 7,X TRACK NUMBER
 BNE DOSEC1 BR NOT TRACK 0
 CMPB #$01
 BHI DOSEC1 BR NOT SECTOR 0 OR 1

 DECB
 STAB 9,X SECTOR NUMBER
 INCB
 BRA DOSEC2

DOSEC1 STAB 9,X SECTOR NUMBER
DOSEC2 INCB
 TST DBSDF
 BNE DOSEC3 BR DOUBLE SIDED

 CMPB #MAXS0+1 END OF TRACK
 BRA DOSEC4

DOSEC3 CMPB #MAXS1+1 END OF TRACK
DOSEC4 BNE DOSEC7 BR IF NOT
 INCA INC SECTOR NUMBER
 LDAB #1 RESET SECTOR NUMBER
 CMPA #MAXTRK END OF DISK
 BNE DOSEC7 BR IF NOT
 CLRA SET ZERO FORWARD LINK
 CLRB

DOSEC7 STAA 30,X FOWARD LINK
 STAB 31,X
 LDAA #$FB ADDRESS MARK
 STAA 29,X JUST BEFORE DATA
 LDAA #$F7 SET CRC CODE
 STAA 11,X
 LDAB #128
 BSR ADDXB ADD 128 TO INDEX
 STAA 128+30,X STORE "F7" AFTER 256 BYTES
 LDAB #172


