*
BEGIN LDAA QUECNT
 CMPA #12 IS QUEUE FULL?
 BNE NOTFUL NOPE
 JMP QUEFUL YUP - SO DO IT
*
NOTFUL LDAA POUT
 CMPA #$39 IS PRINT.SYS LOADED?
 BNE LOADED YES IT IS.....
 LDX #FCB NO - SO LOAD IT.
 LDAA #$01
 STAA $00,X
 JSR FMS
 BEQ NOERR1 NO ERRORS
 LDAA $01,X GET ERROR CODE.
 CMPA #$04 IS ERROR = FILE NOT FOUND?
 BEQ FNFERR YES
 JMP ERROR OTHER TYPE OF ERROR
*
FNFERR LDX #FNFMSG FILE NOT FOUND
 JMP SHWMSG
*
NOERR1 LDAA #$FF
 STAA $3B,X SPACE COMPRESS FLAG
 JSR LOAD
*
LOADED LDX #FCB
 LDAA #$01
 STAA TEMP
 JSR GETFIL GET FILE NAME FROM LINBUF
 BCS ERROR .TO BE SPOOLED.
 LDAA #$0B
 JSR SETEXT SET EXT = .OUT
 LDAA #$01
 STAA $00,X SET FUNCT = OPEN FOR READ
 JSR FMS
 BNE ERROR
 LDAA #$04 SET FUNCT = CLOSE FILE
 STAA $00,X .ONLY REMOVES IT FROM CHAIN
 JSR FMS .OF OPENED FILES
 BNE ERROR
 LDAA $03,X GET DRIVE NUMBER
 PSHA SAVE IT FOR NOW
 LDAA $11,X STARTING DISK ADDR OF FILE
 LDAB $12,X
 LDX QUEPTR
 CLR $03,X QUE ACTIVITY FLAG
 STAA $01,X FILE TRACK NUMBER
 STAB $02,X FILE SECTOR NUMBER
 PULA  RESTORE DRIVE NUMBER
 STAA $00,X FILE DRIVE NUMBER
 LDAA LSTTRM
*
