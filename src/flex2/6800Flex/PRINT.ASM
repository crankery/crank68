*
* THIS IS THE PRINT COMMAND THAT WILL SET UP
* .OUT FILES INTO THE QUEUE TO PRINTED.
*
MA02C  EQU $A02C
MA032  EQU $A032
*
* SPOOLER LINKAGE ADDRESSES
*
MA706  EQU $A706
QUEPTR  EQU $A717 QUEUE POINTER
QUECNT EQU $A71B NUMBER OF FILES IN QUEUE
QSTART  EQU $A810 BEGINING OF PRINT QUEUE
*
* FLEX LINKAGE ADDRESSESS
*
FCB    EQU $A840
EOL    EQU $AC02
TEMP   EQU $AC0D
LSTTRM EQU $AC11
PINIT  EQU $ACC0
POUT   EQU $ACE4
PFLAG  EQU $ACFC
MACFE  EQU $ACFE
WARMS  EQU $AD03
PSTRNG EQU $AD1E
NXTCHR EQU $AD27
GETFIL EQU $AD2D
LOAD   EQU $AD30
SETEXT EQU $AD33
RPTERR EQU $AD3F
INDEC  EQU $AD48
FMS    EQU $B406
MPTADR EQU $BEA9
